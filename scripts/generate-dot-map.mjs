const LON_MIN = -170,
  LON_MAX = 180,
  LAT_MAX = 83,
  LAT_MIN = -56,
  STEP = 4;

function inside(point, polygon) {
  const [x, y] = point;
  let result = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) result = !result;
  }
  return result;
}

const cols = Math.round((LON_MAX - LON_MIN) / STEP);
const rows = Math.round((LAT_MAX - LAT_MIN) / STEP);
let path = "";
let count = 0;
for (let r = 0; r <= rows; r++) {
  for (let c = 0; c <= cols; c++) {
    const lon = LON_MIN + c * STEP;
    const lat = LAT_MAX - r * STEP;
    if (Object.values(CONTINENTS).some((poly) => inside([lon, lat], poly))) {
      path += `M${c} ${r}h0`;
      count++;
    }
  }
}

const out = `// GENERATED by scripts/generate-dot-map.mjs — do not edit by hand.
export const DOT_MAP_VIEWBOX = "-1 -1 ${cols + 2} ${rows + 2}";
export const DOT_MAP_PATH = "${path}";
`;
writeFileSync(new URL("../app/components/n/dot-map/dot-map-path.ts", import.meta.url), out);
console.log(`dots: ${count}, bytes: ${out.length}`);
