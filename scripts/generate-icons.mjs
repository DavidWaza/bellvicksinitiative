const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ASSETS = join(ROOT, "node_modules/@phosphor-icons/core/assets");

/** Icons used with weight="fill": any quoted icon name on an NIcon tag that has weight="fill". */
function findFillIcons() {
  const used = new Set();
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (path.endsWith(".vue")) {
        const src = readFileSync(path, "utf8");
        for (const tag of src.match(/<NIcon\b[^>]*>/g) ?? []) {
          if (!/weight="fill"/.test(tag)) continue;
          for (const m of tag.matchAll(/['"]([a-zA-Z]+)['"]/g))
            if (m[1] in ICON_SOURCES) used.add(m[1]);
        }
      }
    }
  };
  walk(join(ROOT, "app"));
  return used;
}

function inner(file) {
  const svg = readFileSync(file, "utf8");
  return svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .trim();
}

const fill = findFillIcons();
const entries = Object.entries(ICON_SOURCES).map(([name, ph]) => {
  const weights = {
    regular: inner(join(ASSETS, "regular", `${ph}.svg`)),
    duotone: inner(join(ASSETS, "duotone", `${ph}-duotone.svg`)),
  };
  if (fill.has(name)) weights.fill = inner(join(ASSETS, "fill", `${ph}-fill.svg`));
  return `  ${name}: ${JSON.stringify(weights)},`;
});

const out = `// GENERATED by scripts/generate-icons.mjs from @phosphor-icons/core (MIT) — do not edit by hand.
// Add an icon in that script's ICON_SOURCES and re-run it.
export const ICON_PATHS = {
${entries.join("\n")}
} as const satisfies Record<string, { regular: string; duotone: string; fill?: string }>;
`;
